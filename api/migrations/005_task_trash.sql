-- 지운 시각. 비어 있으면 살아 있는 할 일, 차 있으면 휴지통에 있는 할 일.
-- 휴지통의 할 일은 딸린 실행 기록·완료 기록과 함께 그대로 남아 있다가,
-- 되돌리면 전부 원래대로 돌아온다. 30일이 지나거나 '영구 삭제'하면 그때 실제로 지운다.
alter table tasks add column deleted_at timestamptz;

-- 살아 있는 할 일만 빠르게 찾기 (대부분의 화면이 이 조건으로 읽음)
create index tasks_alive_by_plan on tasks (plan_id) where deleted_at is null;
